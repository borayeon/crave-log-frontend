/**
 * Translate a key into the given language with fallback support and parameter interpolation
 * @param {string} key - Translation key
 * @param {string} lang - 'ko' | 'en' | 'zh'
 * @param {string|object} [fallbackOrParams] - Fallback text or params object { count: 5 }
 * @param {object} [params] - Params object { count: 5 }
 * @returns {string}
 */
export const translate = (key, lang = 'ko', fallbackOrParams = '', params = {}) => {
  let fallback = '';
  let actualParams = {};

  if (typeof fallbackOrParams === 'object' && fallbackOrParams !== null) {
    actualParams = fallbackOrParams;
    if (typeof params === 'string') {
      fallback = params;
    }
  } else if (typeof fallbackOrParams === 'string') {
    fallback = fallbackOrParams;
    if (typeof params === 'object' && params !== null) {
      actualParams = params;
    }
  }

  const currentLangDict = translations[lang] || translations.ko;
  let text = currentLangDict?.[key];

  if (text === undefined) {
    text = translations.ko?.[key];
  }

  if (text === undefined) {
    text = fallback || key;
  }

  // Parameter interpolation: {key}
  if (actualParams && typeof text === 'string') {
    Object.keys(actualParams).forEach((pKey) => {
      text = text.replace(new RegExp(`\\{${pKey}\\}`, 'g'), actualParams[pKey]);
    });
  }

  return text;
};

/**
 * Detect browser initial language
 * @returns {'ko' | 'en' | 'zh'}
 */
export const detectInitialLang = () => {
  if (typeof window === 'undefined') return 'ko';
  const saved = localStorage.getItem('cravelog_lang');
  if (saved && (saved === 'ko' || saved === 'en' || saved === 'zh')) {
    return saved;
  }
  const navLang = (navigator.language || navigator.userLanguage || '').toLowerCase();
  if (navLang.startsWith('zh')) return 'zh';
  if (navLang.startsWith('en')) return 'en';
  return 'ko';
};
